/// Generates the Dart client (models and operations) from the TAKE-TUK OpenAPI document.
///
/// It supports exactly the schema constructs the backend emits (ADR-0014): objects, arrays,
/// string enums, `nullable`, single-`$ref` `allOf`, discriminated `oneOf` request bodies, maps and
/// primitives. Anything else stops generation with an error instead of producing a lossy client.
library;

import 'package:dart_style/dart_style.dart';

/// Operations for back-office use are left out of the mobile client (admin web is separate).
const _excludedTags = {'admin'};

final class GeneratedClient {
  const GeneratedClient({required this.models, required this.api});

  final String models;
  final String api;
}

GeneratedClient generateClient(Map<String, Object?> document) {
  final generator = _Generator(document);
  final api = generator.operations();
  final models = generator.models();
  final formatter = DartFormatter(
    languageVersion: DartFormatter.latestLanguageVersion,
  );
  return GeneratedClient(
    models: formatter.format(models),
    api: formatter.format(api),
  );
}

const _header = '''
// GENERATED by packages/taketuk_api/tool/generate.dart from docs/api/openapi.json.
// Do not edit by hand: change the backend, run `npm run openapi` in backend/, then
// `dart run tool/generate.dart` in packages/taketuk_api/.
''';

sealed class _Type {
  const _Type();

  String get dart;

  /// Whether values need conversion between Dart and JSON.
  bool get converts;
}

final class _Primitive extends _Type {
  const _Primitive(this.dart, this.reader);

  @override
  final String dart;
  final String reader;

  @override
  bool get converts => false;
}

final class _Named extends _Type {
  const _Named(this.dart, {required this.isEnum});

  @override
  final String dart;
  final bool isEnum;

  @override
  bool get converts => true;
}

final class _ListOf extends _Type {
  const _ListOf(this.item);

  final _Type item;

  @override
  String get dart => 'List<${item.dart}>';

  @override
  bool get converts => item.converts;
}

final class _MapOf extends _Type {
  const _MapOf(this.value);

  final _Type value;

  @override
  String get dart => 'Map<String, ${value.dart}>';

  @override
  bool get converts => value.converts;
}

final class _Any extends _Type {
  const _Any();

  @override
  String get dart => 'Object?';

  @override
  bool get converts => false;
}

final class _Field {
  const _Field({
    required this.json,
    required this.type,
    required this.required,
    required this.nullable,
    this.description,
  });

  final String json;
  final _Type type;

  /// Present in every JSON object (it may still be null when [nullable]).
  final bool required;
  final bool nullable;
  final String? description;

  bool get optionalInDart => nullable || !required;
}

sealed class _Definition {
  const _Definition(this.name, this.description);

  final String name;
  final String? description;
}

final class _Class extends _Definition {
  _Class(
    super.name,
    super.description,
    this.fields, {
    this.parent,
    this.discriminator,
  });

  final List<_Field> fields;
  final String? parent;

  /// For a `oneOf` variant: the discriminator property and its constant value.
  final ({String json, String value})? discriminator;
}

final class _Enum extends _Definition {
  _Enum(super.name, super.description, this.values);

  final List<String> values;
}

final class _Sealed extends _Definition {
  _Sealed(super.name, super.description, this.discriminator, this.variants);

  final String discriminator;
  final List<_Class> variants;
}

final class _Generator {
  _Generator(this.document)
    : components = _map(
        _map(document['components'], 'components')['schemas'],
        'schemas',
      );

  final Map<String, Object?> document;
  final Map<String, Object?> components;
  final Map<String, _Definition> definitions = {};

  /// Call after [operations]: only types reachable from generated operations are emitted.
  String models() {
    final out = StringBuffer(_header)
      ..writeln('// ignore_for_file: lines_longer_than_80_chars')
      ..writeln()
      ..writeln("import '../json.dart';")
      ..writeln();
    _writeProblemCodes(out);
    final names = definitions.keys.toList()..sort();
    for (final name in names) {
      switch (definitions[name]!) {
        case final _Class definition when definition.parent == null:
          _writeClass(out, definition);
        case final _Class _:
          break; // written with its sealed parent
        case final _Enum definition:
          _writeEnum(out, definition);
        case final _Sealed definition:
          _writeSealed(out, definition);
      }
    }
    return out.toString();
  }

  String operations() {
    final groups = <String, List<String>>{};
    final paths = _map(document['paths'], 'paths');
    for (final path in paths.keys) {
      final item = _map(paths[path], path);
      for (final method in ['get', 'post', 'put', 'patch', 'delete']) {
        final operation = item[method];
        if (operation == null) continue;
        final op = _map(operation, '$method $path');
        final tags = (op['tags'] as List<Object?>? ?? const []).cast<String>();
        if (tags.any(_excludedTags.contains)) continue;
        final id = op['operationId']! as String;
        final [group, name] = id.split('.');
        groups
            .putIfAbsent(group, () => [])
            .add(_operation(method, path, op, name, id));
      }
    }

    final out = StringBuffer(_header)
      ..writeln()
      ..writeln("import '../json.dart';")
      ..writeln("import '../transport.dart';")
      ..writeln("import 'models.dart';")
      ..writeln();
    final groupNames = groups.keys.toList()..sort();
    out
      ..writeln('/// Entry point: one property per API area.')
      ..writeln('final class TaketukApi {')
      ..writeln('  TaketukApi(ApiTransport transport)')
      ..write('    : ')
      ..writeln(
        groupNames
            .map((g) => '$g = ${_pascal(g)}Api(transport)')
            .join(',\n      '),
      )
      ..writeln(';')
      ..writeln();
    for (final group in groupNames) {
      out.writeln('  final ${_pascal(group)}Api $group;');
    }
    out
      ..writeln('}')
      ..writeln();
    for (final group in groupNames) {
      out
        ..writeln('final class ${_pascal(group)}Api {')
        ..writeln('  const ${_pascal(group)}Api(this._transport);')
        ..writeln()
        ..writeln('  final ApiTransport _transport;')
        ..writeln();
      for (final method in groups[group]!) {
        out.writeln(method);
      }
      out.writeln('}');
    }
    return out.toString();
  }

  String _operation(
    String method,
    String path,
    Map<String, Object?> op,
    String name,
    String operationId,
  ) {
    final typePrefix = _pascal(operationId.replaceAll('.', '_'));
    final parameters = (op['parameters'] as List<Object?>? ?? const [])
        .map((p) => _map(p, '$operationId parameter'))
        .toList();
    final positional = <String>[];
    final named = <String>[];
    final query = <String>[];
    final headers = <String>[];

    // Path parameters, in the order they appear in the template.
    var pathExpression = path;
    for (final match in RegExp(r'\{(\w+)\}').allMatches(path)) {
      final variable = match[1]!;
      final declared = parameters.any(
        (p) => p['in'] == 'path' && p['name'] == variable,
      );
      if (!declared) {
        throw StateError(
          '$operationId: path variable {$variable} is not declared',
        );
      }
      positional.add('String $variable');
      pathExpression = pathExpression.replaceFirst(
        '{$variable}',
        '\${Uri.encodeComponent($variable)}',
      );
    }

    String? bodyType;
    final requestBody = op['requestBody'];
    if (requestBody != null) {
      final schema = _jsonSchema(
        _map(requestBody, '$operationId body'),
        operationId,
      );
      final type = _typeOf(schema, '${typePrefix}Request');
      bodyType = type.dart;
      positional.add('${type.dart} body');
    }

    for (final parameter in parameters) {
      final paramName = parameter['name']! as String;
      final required = parameter['required'] == true;
      switch (parameter['in']) {
        case 'path':
          break;
        case 'header':
          final dartName = _camel(paramName);
          if (paramName != 'Idempotency-Key') {
            throw StateError(
              '$operationId: unsupported header parameter $paramName',
            );
          }
          named.add(
            required ? 'required String $dartName' : 'String? $dartName',
          );
          headers.add(
            required
                ? "'$paramName': $dartName"
                : "if ($dartName case final value?) '$paramName': value",
          );
        case 'query':
          final type = _typeOf(
            _map(parameter['schema'], '$operationId $paramName'),
            '$typePrefix${_pascal(paramName)}',
          );
          final text = switch (type) {
            _Primitive(dart: 'String') => 'value',
            _Primitive() => "'\$value'",
            _Named(isEnum: true) => 'value.toJson()',
            _ => throw StateError(
              '$operationId: unsupported query type for $paramName',
            ),
          };
          named.add(
            required
                ? 'required ${type.dart} $paramName'
                : '${type.dart}? $paramName',
          );
          query.add(switch ((required, text)) {
            (true, _) => "'$paramName': ${text.replaceAll('value', paramName)}",
            (false, 'value') => "'$paramName': ?$paramName",
            (false, _) =>
              "if ($paramName case final value?) '$paramName': $text",
          });
        default:
          throw StateError(
            '$operationId: unsupported parameter location ${parameter['in']}',
          );
      }
    }

    final (responseType, responseDecode) = _successResponse(
      op,
      operationId,
      typePrefix,
    );
    final authenticated =
        (op['security'] as List<Object?>? ?? const []).isNotEmpty;

    final docs = StringBuffer();
    final summary = op['summary'] as String?;
    final description = op['description'] as String?;
    if (summary != null) _docComment(docs, summary, indent: '  ');
    if (description != null) {
      docs.writeln('  ///');
      _docComment(docs, description, indent: '  ');
    }
    docs.writeln('  ///');
    docs.writeln('  /// `${method.toUpperCase()} $path` (`$operationId`).');

    final params = [
      ...positional,
      if (named.isNotEmpty) '{${named.join(', ')}}',
    ].join(', ');
    final call = StringBuffer()
      ..write(
        "await _transport.send('${method.toUpperCase()}', '$pathExpression'",
      );
    if (query.isNotEmpty) call.write(', query: {${query.join(', ')}}');
    if (headers.isNotEmpty) call.write(', headers: {${headers.join(', ')}}');
    if (bodyType != null) call.write(', body: body.toJson()');
    if (!authenticated) call.write(', authenticated: false');
    call.write(')');

    final body = responseDecode == null
        ? '    $call;'
        : '    final json = $call;\n    return _transport.decode(json, (json) => $responseDecode);';
    return '$docs  Future<$responseType> $name($params) async {\n$body\n  }\n';
  }

  (String, String?) _successResponse(
    Map<String, Object?> op,
    String operationId,
    String typePrefix,
  ) {
    final responses = _map(op['responses'], '$operationId responses');
    final success =
        responses.keys.where((code) => code.startsWith('2')).toList()..sort();
    if (success.isEmpty) {
      throw StateError('$operationId has no success response');
    }
    final response = _map(
      responses[success.first],
      '$operationId ${success.first}',
    );
    if (response['content'] == null) return ('void', null);
    final type = _typeOf(
      _jsonSchema(response, operationId),
      '${typePrefix}Response',
    );
    return (type.dart, _decode('json', type, operationId));
  }

  Map<String, Object?> _jsonSchema(
    Map<String, Object?> holder,
    String context,
  ) {
    final content = _map(holder['content'], '$context content');
    final json = content['application/json'];
    if (json == null) {
      throw StateError('$context: only application/json is supported');
    }
    return _map(_map(json, context)['schema'], '$context schema');
  }

  _Type _typeOf(Map<String, Object?> schema, String name) {
    if (schema[r'$ref'] case final String ref) return _ref(ref);
    if (schema['allOf'] case final List<Object?> all) {
      if (all.length != 1) {
        throw StateError('$name: allOf with ${all.length} members');
      }
      return _typeOf(_map(all.single, name), name);
    }
    if (schema['oneOf'] case final List<Object?> variants) {
      return _sealed(schema, variants, name);
    }
    switch (schema['type']) {
      case 'object':
        if (schema['properties'] is Map) return _class(schema, name);
        final additional = schema['additionalProperties'];
        if (additional is Map<String, Object?> && additional.isNotEmpty) {
          return _MapOf(_typeOf(additional, '${name}Value'));
        }
        return const _MapOf(_Any());
      case 'array':
        return _ListOf(
          _typeOf(_map(schema['items'], '$name items'), '${name}Item'),
        );
      case 'string':
        if (schema['enum'] case final List<Object?> values) {
          return _enum(
            name,
            schema['description'] as String?,
            values.cast<String>(),
          );
        }
        return const _Primitive('String', 'readString');
      case 'integer':
        return const _Primitive('int', 'readInt');
      case 'number':
        return const _Primitive('double', 'readDouble');
      case 'boolean':
        return const _Primitive('bool', 'readBool');
      case null when schema.keys.every((k) => k == 'description'):
        return const _Any();
    }
    throw StateError('$name: unsupported schema $schema');
  }

  _Type _ref(String ref) {
    const prefix = '#/components/schemas/';
    if (!ref.startsWith(prefix)) throw StateError('unsupported reference $ref');
    final name = ref.substring(prefix.length);
    final schema = _map(components[name], ref);
    final existing = definitions[name];
    if (existing == null) _typeOf(schema, name);
    return _Named(name, isEnum: definitions[name] is _Enum);
  }

  _Named _class(
    Map<String, Object?> schema,
    String name, {
    String? parent,
    String? discriminator,
  }) {
    _reserve(name);
    final required = (schema['required'] as List<Object?>? ?? const [])
        .cast<String>()
        .toSet();
    final properties = _map(schema['properties'], name);
    final fields = <_Field>[];
    ({String json, String value})? constant;
    for (final entry in properties.entries) {
      final property = _map(entry.value, '$name.${entry.key}');
      if (entry.key == discriminator) {
        constant = (
          json: entry.key,
          value: (property['enum']! as List<Object?>).single! as String,
        );
        continue;
      }
      fields.add(
        _Field(
          json: entry.key,
          type: _typeOf(property, '$name${_pascal(entry.key)}'),
          required: required.contains(entry.key),
          nullable: property['nullable'] == true,
          description: property['description'] as String?,
        ),
      );
    }
    definitions[name] = _Class(
      name,
      schema['description'] as String?,
      fields,
      parent: parent,
      discriminator: constant,
    );
    return _Named(name, isEnum: false);
  }

  _Named _enum(String name, String? description, List<String> values) {
    final existing = definitions[name];
    if (existing is _Enum && existing.values.join(',') == values.join(',')) {
      return _Named(name, isEnum: true);
    }
    _reserve(name);
    definitions[name] = _Enum(name, description, values);
    return _Named(name, isEnum: true);
  }

  _Named _sealed(
    Map<String, Object?> schema,
    List<Object?> variants,
    String name,
  ) {
    _reserve(name);
    final members = variants.map((v) => _map(v, name)).toList();
    // The discriminator is the required property that every variant fixes to a single value.
    final candidates = _map(members.first['properties'], name).keys.where(
      (key) => members.every((m) {
        final property = _map(m['properties'], name)[key];
        final required = (m['required'] as List<Object?>? ?? const []).contains(
          key,
        );
        return required &&
            property is Map<String, Object?> &&
            property['enum'] is List<Object?> &&
            (property['enum']! as List<Object?>).length == 1;
      }),
    );
    if (candidates.length != 1) {
      throw StateError('$name: oneOf without a single discriminator');
    }
    final discriminator = candidates.single;
    definitions[name] = _Sealed(
      name,
      schema['description'] as String?,
      discriminator,
      [],
    );
    final classes = <_Class>[];
    for (final member in members) {
      final value =
          ((_map(member['properties'], name)[discriminator]!
                          as Map<String, Object?>)['enum']!
                      as List<Object?>)
                  .single!
              as String;
      final variantName = '$name${_pascal(value)}';
      _class(member, variantName, parent: name, discriminator: discriminator);
      classes.add(definitions[variantName]! as _Class);
    }
    definitions[name] = _Sealed(
      name,
      schema['description'] as String?,
      discriminator,
      classes,
    );
    return _Named(name, isEnum: false);
  }

  void _reserve(String name) {
    if (definitions.containsKey(name)) {
      throw StateError('two schemas generate the type $name');
    }
  }

  String _decode(String expression, _Type type, String path) => switch (type) {
    _Primitive(:final reader) => "$reader($expression, '$path')",
    _Named(:final dart, isEnum: true) =>
      "$dart.fromJson(readString($expression, '$path'))",
    _Named(:final dart) => "$dart.fromJson(readObject($expression, '$path'))",
    _ListOf(:final item) =>
      "readList($expression, '$path').map((e) => ${_decode('e', item, '$path[]')}).toList()",
    _MapOf(:final value) =>
      "readObject($expression, '$path').map((k, e) => MapEntry(k, ${_decode('e', value, '$path{}')}))",
    _Any() => expression,
  };

  String _encode(String expression, _Type type) => switch (type) {
    _ when !type.converts => expression,
    _Named() => '$expression.toJson()',
    _ListOf(:final item) =>
      '[for (final e in $expression) ${_encode('e', item)}]',
    _MapOf(:final value) =>
      '{for (final MapEntry(:key, value: e) in $expression.entries) key: ${_encode('e', value)}}',
    _Primitive() || _Any() => expression,
  };

  void _writeProblemCodes(StringBuffer out) {
    final registry =
        (document['x-taketuk-problem-codes'] as List<Object?>? ?? const [])
            .map((e) => _map(e, 'x-taketuk-problem-codes'))
            .toList();
    if (registry.isEmpty) {
      throw StateError('the document has no x-taketuk-problem-codes');
    }
    out
      ..writeln(
        '/// Every stable problem `code` the API can return (API_CONVENTIONS §6).',
      )
      ..writeln('abstract final class ProblemCodes {');
    for (final entry in registry) {
      final code = entry['code']! as String;
      out
        ..writeln('  /// HTTP ${entry['status']}: ${entry['title']}.')
        ..writeln("  static const ${_camel(code.toLowerCase())} = '$code';");
    }
    out
      ..writeln('}')
      ..writeln();
  }

  void _writeClass(
    StringBuffer out,
    _Class definition, {
    String? extendsClass,
  }) {
    final name = definition.name;
    if (definition.description case final description?) {
      _docComment(out, description);
    }
    out.writeln(
      extendsClass == null
          ? 'final class $name {'
          : 'final class $name extends $extendsClass {',
    );
    // Constructor.
    if (definition.fields.isEmpty) {
      out.writeln('  const $name();');
    } else {
      out.writeln('  const $name({');
      for (final field in definition.fields) {
        out.writeln(
          field.required
              ? '    required this.${field.json},'
              : '    this.${field.json},',
        );
      }
      out.writeln('  });');
    }
    out.writeln();
    // fromJson.
    if (definition.fields.isEmpty) {
      out
        ..writeln(
          '  factory $name.fromJson(Map<String, Object?> _) => const $name();',
        )
        ..writeln();
    } else {
      out.writeln(
        '  factory $name.fromJson(Map<String, Object?> json) => $name(',
      );
      for (final field in definition.fields) {
        final path = '$name.${field.json}';
        final read = field.optionalInDart
            ? "switch (json['${field.json}']) { null => null, final value => ${_decode('value', field.type, path)} }"
            : _decode("json['${field.json}']", field.type, path);
        out.writeln('    ${field.json}: $read,');
      }
      out
        ..writeln('  );')
        ..writeln();
    }
    // Fields.
    for (final field in definition.fields) {
      if (field.description case final description?) {
        _docComment(out, description, indent: '  ');
      }
      out.writeln(
        '  final ${field.type.dart}${field.optionalInDart ? '?' : ''} ${field.json};',
      );
    }
    if (definition.fields.isNotEmpty) out.writeln();
    // toJson.
    if (extendsClass != null) out.writeln('  @override');
    out.writeln('  Map<String, Object?> toJson() => {');
    if (definition.discriminator case final discriminator?) {
      out.writeln("    '${discriminator.json}': '${discriminator.value}',");
    }
    for (final field in definition.fields) {
      final key = "'${field.json}'";
      if (!field.required && !field.type.converts) {
        out.writeln('    $key: ?${field.json},');
      } else if (!field.required) {
        out.writeln(
          '    if (${field.json} case final value?) $key: ${_encode('value', field.type)},',
        );
      } else if (field.nullable && field.type.converts) {
        out.writeln(
          '    $key: switch (${field.json}) { final value? => ${_encode('value', field.type)}, null => null },',
        );
      } else {
        out.writeln('    $key: ${_encode(field.json, field.type)},');
      }
    }
    out
      ..writeln('  };')
      ..writeln('}')
      ..writeln();
  }

  void _writeEnum(StringBuffer out, _Enum definition) {
    final name = definition.name;
    if (definition.description case final description?) {
      _docComment(out, description);
    }
    out.writeln('enum $name {');
    for (final value in definition.values) {
      out.writeln("  ${_enumMember(value)}('$value'),");
    }
    out
      ..writeln()
      ..writeln(
        '  /// A value from a newer API version: clients must tolerate it (API_CONVENTIONS §1).',
      )
      ..writeln(r"  $unknown('');")
      ..writeln()
      ..writeln('  const $name(this.value);')
      ..writeln()
      ..writeln('  factory $name.fromJson(String value) =>')
      ..writeln(
        r'      values.firstWhere((e) => e != $unknown && e.value == value, orElse: () => $unknown);',
      )
      ..writeln()
      ..writeln('  final String value;')
      ..writeln()
      ..writeln(r'  String toJson() => this == $unknown')
      ..writeln(
        "      ? throw StateError('$name.\\\$unknown cannot be sent to the API')",
      )
      ..writeln('      : value;')
      ..writeln('}')
      ..writeln();
  }

  void _writeSealed(StringBuffer out, _Sealed definition) {
    final name = definition.name;
    if (definition.description case final description?) {
      _docComment(out, description);
    }
    out
      ..writeln('sealed class $name {')
      ..writeln('  const $name();')
      ..writeln()
      ..writeln('  factory $name.fromJson(Map<String, Object?> json) =>')
      ..writeln("      switch (json['${definition.discriminator}']) {");
    for (final variant in definition.variants) {
      out.writeln(
        "        '${variant.discriminator!.value}' => ${variant.name}.fromJson(json),",
      );
    }
    out
      ..writeln(
        "        final other => throw FormatException('Unknown $name.${definition.discriminator}: \$other'),",
      )
      ..writeln('      };')
      ..writeln()
      ..writeln('  Map<String, Object?> toJson();')
      ..writeln('}')
      ..writeln();
    for (final variant in definition.variants) {
      _writeClass(out, variant, extendsClass: name);
    }
  }
}

Map<String, Object?> _map(Object? value, String context) {
  if (value is Map<String, Object?>) return value;
  throw StateError('$context: expected an object');
}

void _docComment(StringBuffer out, String text, {String indent = ''}) {
  for (final line in text.trim().split('\n')) {
    out.writeln(line.isEmpty ? '$indent///' : '$indent/// $line');
  }
}

/// `pending_review` → `PendingReview`, `image/jpeg` → `ImageJpeg`, `driverOffers` → `DriverOffers`.
String _pascal(String text) => text
    .split(RegExp('[^A-Za-z0-9]+'))
    .where((part) => part.isNotEmpty)
    .map((part) => part[0].toUpperCase() + part.substring(1))
    .join();

String _camel(String text) {
  final pascal = _pascal(text);
  return pascal[0].toLowerCase() + pascal.substring(1);
}

String _enumMember(String value) =>
    _camel(value == value.toUpperCase() ? value.toLowerCase() : value);
